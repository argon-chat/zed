use std::{
    collections::BTreeSet,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

const MODULES: [(&str, &str); 13] = [
    ("Quad", "quad"),
    ("Shadow", "shadow"),
    ("BlurDownsample", "blur_downsample"),
    ("BlurUpsample", "blur_upsample"),
    ("BlurRect", "blur_rect"),
    ("Underline", "underline"),
    ("PathRasterization", "path_rasterization"),
    ("PathSprite", "path_sprite"),
    ("MonochromeSprite", "monochrome_sprite"),
    ("SubpixelSprite", "subpixel_sprite"),
    ("PolychromeSprite", "polychrome_sprite"),
    ("EmojiRasterization", "emoji_rasterization"),
    ("VnLayer", "vn_layer"),
];
const EFFECTS: [(&str, &str); 3] = [("Frost", "frost"), ("Noise", "noise"), ("Glow", "glow")];

pub(super) fn compile(manifest: &Path, effects: &Path, out: &Path, fxc: &str) {
    println!("cargo:rerun-if-env-changed=GPUI_FXC_PATH");
    println!("cargo:rerun-if-changed=build/native_dx12.rs");
    let source_dir = manifest.join("src");
    let mut inputs = BTreeSet::new();
    let mut bindings = String::from("// Generated by build/native_dx12.rs.\n");
    let mut arms = String::new();
    for (variant, prefix) in MODULES {
        let source = source_dir.join(if prefix == "emoji_rasterization" {
            "color_text_raster.hlsl"
        } else {
            "shaders.hlsl"
        });
        track_inputs(&source, &source_dir, &mut inputs);
        let vertex = format!("native_dx12_{prefix}_vs.cso");
        let fragment = format!("native_dx12_{prefix}_ps.cso");
        stage(
            fxc,
            &source,
            &source_dir,
            &format!("{prefix}_vertex"),
            "vs_5_1",
            &out.join(&vertex),
        );
        stage(
            fxc,
            &source,
            &source_dir,
            &format!("{prefix}_fragment"),
            "ps_5_1",
            &out.join(&fragment),
        );
        arms.push_str(&format!(
            "ShaderModule::{variant} => ({}, {}),\n",
            embedded(&vertex),
            embedded(&fragment)
        ));
    }

    let vertex_source = source_dir.join("effects.hlsl");
    track_inputs(&vertex_source, &source_dir, &mut inputs);
    let effect_vertex = "native_dx12_effect_vs.cso";
    stage(
        fxc,
        &vertex_source,
        &source_dir,
        "effect_vertex",
        "vs_5_1",
        &out.join(effect_vertex),
    );
    bindings.push_str(&format!(
        "pub(super) fn effect_vertex() -> &'static [u8] {{ {} }}\n",
        embedded(effect_vertex)
    ));
    for (variant, name) in EFFECTS {
        let source = effects.join(format!("{name}.hlsl"));
        track_inputs(&source, &source_dir, &mut inputs);
        let fragment = format!("native_dx12_effect_{name}_ps.cso");
        stage(
            fxc,
            &source,
            &source_dir,
            "effect_fragment",
            "ps_5_1",
            &out.join(&fragment),
        );
        arms.push_str(&format!(
            "ShaderModule::Effect(EffectShader::{variant}) => (effect_vertex(), {}),\n",
            embedded(&fragment)
        ));
    }
    bindings.push_str(&format!("pub(super) fn module(module: ShaderModule) -> (&'static [u8], &'static [u8]) {{ match module {{ {arms} }} }}\n"));
    bindings.push_str("#[cfg(test)] pub(super) const INPUTS: &[(&str, u64)] = &[\n");
    for input in inputs {
        let bytes = fs::read(&input)
            .unwrap_or_else(|error| panic!("read shader input {}: {error}", input.display()));
        bindings.push_str(&format!(
            "({:?}, {}),\n",
            input.to_string_lossy(),
            source_hash(&bytes)
        ));
    }
    bindings.push_str("];\n");
    fs::write(out.join("native_dx12_shaders.rs"), bindings)
        .expect("write native D3D12 shader bindings");
}

fn embedded(name: &str) -> String {
    format!("include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{name}\"))")
}

fn track_inputs(source: &Path, source_dir: &Path, seen: &mut BTreeSet<PathBuf>) {
    let source = source
        .canonicalize()
        .unwrap_or_else(|error| panic!("resolve shader input {}: {error}", source.display()));
    if !seen.insert(source.clone()) {
        return;
    }
    println!("cargo:rerun-if-changed={}", source.display());
    let text = fs::read_to_string(&source)
        .unwrap_or_else(|error| panic!("read shader input {}: {error}", source.display()));
    for line in text.lines() {
        let Some(rest) = line.trim_start().strip_prefix('#') else {
            continue;
        };
        let Some(rest) = rest.trim_start().strip_prefix("include") else {
            continue;
        };
        let rest = rest.trim_start();
        let Some(rest) = rest.strip_prefix('"') else {
            continue;
        };
        let Some((name, _)) = rest.split_once('"') else {
            continue;
        };
        let relative = source
            .parent()
            .expect("shader input has a parent")
            .join(name);
        let include = if relative.is_file() {
            relative
        } else {
            source_dir.join(name)
        };
        // Generated Slang HLSL also names NVAPI inside an inactive #ifdef.
        // An active missing include is rejected by FXC itself below.
        if include.is_file() {
            track_inputs(&include, source_dir, seen);
        }
    }
}

fn stage(fxc: &str, source: &Path, source_dir: &Path, entry: &str, profile: &str, output: &Path) {
    let result = Command::new(fxc)
        .args(["/nologo", "/Ges", "/O3", "/T", profile, "/E", entry, "/I"])
        .arg(source_dir)
        .arg("/Fo")
        .arg(output)
        .arg(source)
        .output()
        .unwrap_or_else(|error| panic!("run FXC for native D3D12 {entry} ({profile}): {error}"));
    assert!(
        result.status.success(),
        "native D3D12 shader {entry} ({profile}) failed:\n{}\n{}",
        String::from_utf8_lossy(&result.stdout),
        String::from_utf8_lossy(&result.stderr)
    );
    let artifact = fs::read(output)
        .unwrap_or_else(|error| panic!("read native D3D12 artifact {}: {error}", output.display()));
    assert!(
        artifact.starts_with(b"DXBC"),
        "FXC did not produce DXBC for {entry}"
    );
}

fn source_hash(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x100_0000_01b3)
    })
}
